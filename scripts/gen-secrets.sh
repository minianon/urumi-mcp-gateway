#!/usr/bin/env bash
# Generate random credentials for one environment into deploy/secrets/<env>/ (git-ignored).
# Each file is passed to its Helm release with -f; the charts turn them into Kubernetes Secrets.
#
#   scripts/gen-secrets.sh local            # idempotent: keeps existing files
#   FORCE=1 scripts/gen-secrets.sh local    # rotate everything
#   LLM_API_KEY=gsk_... scripts/gen-secrets.sh local
set -euo pipefail

ENV_NAME="${1:-local}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DIR="$ROOT/deploy/secrets/$ENV_NAME"
mkdir -p "$DIR"

if [[ -f "$DIR/platform.yaml" && "${FORCE:-0}" != "1" ]]; then
  echo "Secrets for '$ENV_NAME' already exist in $DIR (FORCE=1 to regenerate)."
  exit 0
fi

hex() { openssl rand -hex "$1"; }

WOO_MCP_TOKEN="$(hex 32)"
SUPPLIER_MCP_TOKEN="$(hex 32)"
ADMIN_PASSWORD="urumi-$(hex 6)"

umask 077
cat > "$DIR/store.yaml" <<EOF
# Generated by scripts/gen-secrets.sh - DO NOT COMMIT
secrets:
  dbPassword: "$(hex 16)"
  dbRootPassword: "$(hex 16)"
  wpAdminPassword: "$(hex 12)"
  wcConsumerKey: "ck_$(hex 20)"
  wcConsumerSecret: "cs_$(hex 20)"
  mcpToken: "$WOO_MCP_TOKEN"
EOF

cat > "$DIR/supplier.yaml" <<EOF
# Generated by scripts/gen-secrets.sh - DO NOT COMMIT
secrets:
  authToken: "$SUPPLIER_MCP_TOKEN"
EOF

cat > "$DIR/platform.yaml" <<EOF
# Generated by scripts/gen-secrets.sh - DO NOT COMMIT
secrets:
  sessionSecret: "$(hex 32)"
  encryptionKey: "$(openssl rand -base64 32)"
  apiKeyPepper: "$(hex 32)"
  adminPassword: "$ADMIN_PASSWORD"
  postgresPassword: "$(hex 16)"
  # Groq (or any OpenAI-compatible provider) key for the chat agent. Edit this line, then re-run
  # the deploy script; the gateway pods restart automatically (checksum annotation).
  llmApiKey: "${LLM_API_KEY:-}"
  # Shared with the upstream MCP servers' own Secrets: the gateway presents these, nobody else has them.
  upstreamTokens:
    woocommerce: "$WOO_MCP_TOKEN"
    supplier: "$SUPPLIER_MCP_TOKEN"
EOF

echo "Wrote $DIR/{store,supplier,platform}.yaml"
echo "Dashboard admin password: $ADMIN_PASSWORD"
